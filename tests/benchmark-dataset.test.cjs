'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const d=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/benchmarks.json'),'utf8'));
const js=fs.readFileSync(path.join(__dirname,'../src/benchmarks.js'),'utf8');
const datasets=new Set(d.evaluation_datasets.map(x=>x.id));
const evaluators=new Set(d.evaluators.map(x=>x.id));
const judge=d.items.filter(x=>x.group==='judge');
assert.ok(judge.length>=4);
assert.ok(d.evaluation_datasets.length>=4);
assert.ok(judge.every(b=>b.tested===false&&b.result_status==='not_run'));
for(const b of judge){
 assert.ok(b.dataset_ids.length&&b.evaluator_ids.length);
 assert.ok(b.dataset_ids.every(id=>datasets.has(id)));
 assert.ok(b.evaluator_ids.every(id=>evaluators.has(id)));
}
assert.ok(d.evaluation_datasets.every(x=>x.url.startsWith('https://')&&x.gold_label&&x.access==='public'));
assert.ok(js.includes("datasets:'评测集'"));
assert.ok(js.includes("mode==='datasets'?bDatasetRecords()"));
assert.ok(js.includes('${bEvaluationLinks(b)}'));
assert.ok(js.includes('bVerifiedResults(b)'));
assert.ok(js.includes('官方结果快照 · 非本站实测'));
assert.ok(js.includes('本站未实测；不展示虚构分数或模型排名'));
assert.ok(js.includes('外部资料 · 本站未实测'));
const novelty=judge.find(x=>x.id==='novelty-judge-bench');
assert.ok(novelty&&novelty.metric_note.includes('弱标签'));
const dddbench=d.items.find(x=>x.id==='dddbench');
assert.ok(dddbench&&dddbench.group==='pharma');
assert.equal(dddbench.result_url,'https://ddb.insilico.com/');
assert.equal(dddbench.tested,false);
assert.ok(dddbench.metric_note.includes('不得')&&dddbench.boundary.includes('不是独立临床验证'));
assert.ok(!('score' in dddbench)&&!('rank' in dddbench)&&!('best_model' in dddbench));
const dddSource=d.sources.find(x=>x.id==='b-dddbench');
assert.ok(dddSource&&dddSource.url==='https://ddb.insilico.com/'&&dddSource.checked==='2026-11-01');
assert.ok(d.changes.some(x=>x.id==='dddbench-platform-20261028'&&x.benchmarks.includes('dddbench')));
const agentArena=d.items.find(x=>x.id==='agent-arena-overall');
assert.ok(agentArena&&agentArena.result_status==='verified'&&agentArena.tested===false);
assert.equal(agentArena.verified_results.rows.length,10);
assert.equal(agentArena.verified_results.rows[0].model,'Claude Opus 5.5 Max');
assert.equal(agentArena.verified_results.rows[0].time_per_task_minutes,19.5);
assert.ok(agentArena.verified_results.rows[0].output_tokens_per_task>0);
assert.ok(js.includes('P50 time/task'));
assert.ok(js.includes('P50 output/task'));
assert.ok(js.includes('横向滚动查看耗时与输出量'));
const eci=d.items.find(x=>x.id==='epoch-eci');
assert.ok(eci&&eci.verified_results.schema==='generic_metric');
assert.equal(eci.verified_results.rows[0].value,169);
assert.ok(js.includes("r.schema==='generic_metric'"));
console.log('PASS Judge benchmark evaluation registry and UI');
