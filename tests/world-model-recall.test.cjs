'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const data=JSON.parse(fs.readFileSync(path.join(root,'data/models.json'),'utf8'));
const script=fs.readFileSync(path.join(root,'src/models.js'),'utf8');
const a=script.indexOf('function mFrontierRows(');
const b=script.indexOf('function mFrontierCard(',a);
assert(a>=0&&b>a);
const ctx={};
vm.runInNewContext(script.slice(a,b)+'\nthis.rows=mFrontierRows',ctx);
const world=data.frontier_tracks.find(t=>t.id==='world-models');
const all=data.frontier_tracks;
const rows=ctx.rows(world,all,true);
assert(rows.some(x=>x.id==='hjepa-hierarchical-planning'));
assert(rows.some(x=>x.id==='jepa-control-unstable-modes'));
assert(rows.some(x=>x.id==='ami-world-model-progress'));
assert(rows.find(x=>x.id==='ami-world-model-progress')._related_from==='Neo Labs / 新实验室');
assert(!ctx.rows(world,all,false).some(x=>x.id==='ami-world-model-progress'));
assert.equal(all.flatMap(x=>x.items).filter(x=>x.id==='ami-world-model-progress').length,1);
assert.deepEqual([...rows.map(x=>x.date)].sort().reverse(),[...rows.map(x=>x.date)]);
assert(script.includes("selected!==\'all\'"));
console.log('PASS World Model topic includes linked AMI and new primary research without global duplicates');
